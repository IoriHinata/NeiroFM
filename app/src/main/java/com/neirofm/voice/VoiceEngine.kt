package com.neirofm.voice

import android.content.Context

data class Presenter(val id: String, val name: String, val style: String)

class VoiceEngine(context: Context) {
    val presenters = listOf(
        Presenter("alex", "Алекс", "спокойный мужской ведущий"),
        Presenter("maria", "Мария", "энергичная женская ведущая"),
        Presenter("max", "Макс", "сдержанный ночной мужской ведущий")
    )
    private val neuralEngine = NeuralVoiceEngine(context.applicationContext)

    val ready: Boolean get() = neuralEngine.ready
    val installing: Boolean get() = neuralEngine.installing
    val isSpeaking: Boolean get() = neuralEngine.isSpeaking
    val status: String get() = neuralEngine.status
    val lastError: String? get() = neuralEngine.lastError

    /**
     * Speech is always generated by the bundled/downloaded Piper model through sherpa-onnx.
     * There is intentionally no Android TextToSpeech fallback.
     */
    fun speak(
        text: String,
        presenterId: String = "alex",
        onComplete: (() -> Unit)? = null,
        onError: ((String) -> Unit)? = null
    ) = neuralEngine.speak(text, presenterId, onComplete, onError)

    fun installNeuralVoice(onComplete: () -> Unit = {}) {
        neuralEngine.install(onComplete = onComplete)
    }

    fun shutdown() = neuralEngine.release()
}
