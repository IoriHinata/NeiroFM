package com.neirofm.data

import java.util.Calendar
import kotlin.random.Random

data class RadioProgram(val name: String, val presenter: String, val description: String, val startHour: Int, val endHour: Int)

object ProgramCatalog {
    val programs = listOf(
        RadioProgram("Neiro Утро", "maria", "Лёгкий старт, планы на день и музыка", 6, 11),
        RadioProgram("Дневная волна", "alex", "Новости дня без политики, интересные факты и музыка", 11, 17),
        RadioProgram("Вечерний маршрут", "maria", "Истории, разговоры и тематические подкасты", 17, 22),
        RadioProgram("После полуночи", "max", "Спокойные размышления, необычные истории и музыка", 22, 6)
    )

    fun current(hour: Int = Calendar.getInstance().get(Calendar.HOUR_OF_DAY)): RadioProgram =
        programs.firstOrNull { if (it.startHour < it.endHour) hour in it.startHour until it.endHour else hour >= it.startHour || hour < it.endHour }
            ?: programs.first()

    private val topics = listOf(
        "Почему мы запоминаем музыку", "Необычные места нашей планеты", "Как рождаются привычки",
        "История повседневных вещей", "Загадки космоса", "Города будущего", "Почему нам снятся сны",
        "Самые удивительные открытия науки", "Как менялся звукозаписывающий мир", "Маленькие радости обычного дня",
        "Животные с невероятными способностями", "Тайны океана", "Архитектура, которая удивляет",
        "Как устроена память", "Путешествие одной мелодии", "Изобретения, изменившие быт"
    )

    fun createPodcast(program: RadioProgram, random: Random = Random.Default): String {
        val topic = topics.random(random)
        val lead = when (program.presenter) {
            "max" -> "Это Макс, и сегодня ночью предлагаю ненадолго отвлечься от суеты."
            "maria" -> "У микрофона Мария! Я приготовила для вас новую интересную тему."
            else -> "С вами Алекс на NeiroFM. Давайте разберёмся в одной любопытной теме."
        }
        val paragraphs = listOf(
            "$lead Сегодня говорим: $topic.",
            "Начнём с простого. Почти у каждого из нас есть личный опыт, связанный с этой темой. Но за привычными вещами часто скрывается гораздо больше, чем кажется на первый взгляд.",
            "Представьте такую ситуацию: вы замечаете это в обычной жизни, но редко задумываетесь, почему всё устроено именно так. Если посмотреть внимательнее, обнаруживаются интересные детали, неожиданные связи и маленькие открытия.",
            "Есть и другая сторона. У каждого явления есть своя история, люди, эксперименты и случайности, которые постепенно складываются в общую картину. Именно поэтому даже знакомая тема может удивить.",
            "Попробуйте сегодня обратить внимание на эту тему вокруг себя. Возможно, вы заметите то, что раньше проходило мимо. А если у вас есть собственная история, сохраните её — такие наблюдения делают разговор живым.",
            "Это был небольшой выпуск NeiroFM. Спасибо, что провели это время с нами. Впереди музыка, а мы ещё вернёмся с новыми историями."
        )
        return paragraphs.joinToString("\n\n")
    }
}
