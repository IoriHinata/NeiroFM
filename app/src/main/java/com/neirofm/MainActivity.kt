private fun formatMs(ms:Long):String { val total=(ms/1000).coerceAtLeast(0); val h=total/3600; val m=(total%3600)/60; val s=total%60; return String.format(java.util.Locale.ROOT,"%02d:%02d:%02d",h,m,s) }
