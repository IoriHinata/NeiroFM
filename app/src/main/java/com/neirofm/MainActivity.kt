 private val studioReceiver = object : BroadcastReceiver() {
  override fun onReceive(context: Context?, intent: Intent?) { refreshStudio() }
 }
 private fun refreshStudio() {
  val p = getSharedPreferences("neirofm_studio", MODE_PRIVATE)
  studioMode = p.getString("mode", "BUFFER_ONLY") ?: "BUFFER_ONLY"
  studioMessage = p.getString("message", "Ожидание эфира") ?: "Ожидание эфира"
  studioBufferMs = p.getLong("buffered_ms", 0L)
  studioOfflineMs = p.getLong("offline_ms", 0L)
  studioInternet = p.getBoolean("internet", false)
  studioGenerated = p.getInt("generated_count", 0)
  studioVoiceStatus = getSharedPreferences("neirofm_voice", MODE_PRIVATE).getString("status", "Голосовые модели ещё не проверены") ?: "Голосовые модели ещё не проверены"
  studioModelReady = p.getBoolean("model_ready", false)
  studioModelInstalling = p.getBoolean("model_installing", false)
  val bufferStore = AudioBufferStore(this)
  studioQueue = runCatching { bufferStore.pending().take(12) }.getOrDefault(emptyList())
  bufferStore.close()
  studioRevision++
 }
 private val voiceStatusReceiver = object : BroadcastReceiver() {
  override fun onReceive(context: Context?, intent: Intent?) {
   voiceStatus = intent?.getStringExtra("status") ?: voiceStatus
  }
 }
 private var folderType = "music"
 private val folder=registerForActivityResult(ActivityResultContracts.OpenDocumentTree()){u->if(u!=null){contentResolver.takePersistableUriPermission(u,Intent.FLAG_GRANT_READ_URI_PERMISSION);val a=DocumentFile.fromTreeUri(this,u)?.listFiles()?.filter{it.isFile&&it.name?.substringAfterLast('.', "")?.lowercase() in listOf("mp3","m4a","ogg","wav","flac","aac")}?.map{it.uri.toString()}.orEmpty();RadioController.setLibrary(this,folderType,a);libraryRevision++}}
 private val txt=registerForActivityResult(ActivityResultContracts.OpenDocument()){u->if(u!=null)runCatching{contentResolver.takePersistableUriPermission(u,Intent.FLAG_GRANT_READ_URI_PERMISSION);val n=DocumentFile.fromSingleUri(this,u)?.name?: "script.txt";val t=contentResolver.openInputStream(u)?.use{ScriptLibrary.decodeUtf8(it.readBytes())}.orEmpty();ScriptLibrary.import(this,u,n,t);libraryRevision++}}
 private val zip=registerForActivityResult(ActivityResultContracts.OpenDocument()){u->if(u!=null)runCatching{
  contentResolver.takePersistableUriPermission(u,Intent.FLAG_GRANT_READ_URI_PERMISSION)
  var imported=0
  ZipInputStream(contentResolver.openInputStream(u)!!).use{archive->
   var entry=archive.nextEntry
   while(entry!=null){
    if(!entry.isDirectory && entry.name.lowercase().endsWith(".txt")){
     val body=ScriptLibrary.decodeUtf8(archive.readBytes())
     if(ScriptLibrary.import(this,u,entry.name.substringAfterLast('/'),body)!=null) imported++
    }
    archive.closeEntry()
    entry=archive.nextEntry
   }
  }
  libraryRevision++
  Toast.makeText(this,"Импортировано сценариев: $imported",Toast.LENGTH_LONG).show()
 }.onFailure{Toast.makeText(this,"Ошибка ZIP/UTF-8: ${it.message}",Toast.LENGTH_LONG).show()}}
 private val maxVoiceFile=registerForActivityResult(ActivityResultContracts.OpenDocument()){u->if(u!=null)runCatching{
  contentResolver.takePersistableUriPermission(u,Intent.FLAG_GRANT_READ_URI_PERMISSION)
  RadioController.importMaxVoice(this,u)
  Toast.makeText(this,"Архив Макса передан на проверку и установку",Toast.LENGTH_LONG).show()
 }.onFailure{Toast.makeText(this,"Не удалось открыть архив: ${it.message}",Toast.LENGTH_LONG).show()}}
 @Suppress("DEPRECATION")
 override fun onStart(){
  super.onStart()
  val voiceFilter=IntentFilter("com.neirofm.action.VOICE_STATUS")
  val studioFilter=IntentFilter("com.neirofm.action.STUDIO_STATUS")
  if(Build.VERSION.SDK_INT>=33){registerReceiver(voiceStatusReceiver,voiceFilter,Context.RECEIVER_NOT_EXPORTED);registerReceiver(studioReceiver,studioFilter,Context.RECEIVER_NOT_EXPORTED)}
  else {registerReceiver(voiceStatusReceiver,voiceFilter);registerReceiver(studioReceiver,studioFilter)}
 }
 override fun onStop(){unregisterReceiver(voiceStatusReceiver);unregisterReceiver(studioReceiver);super.onStop()}
 override fun onResume(){super.onResume();voiceStatus=getSharedPreferences("neirofm_voice",MODE_PRIVATE).getString("status","Состояние нейроголоса ещё не получено").orEmpty();refreshStudio()}
 override fun onCreate(savedInstanceState:Bundle?) {
